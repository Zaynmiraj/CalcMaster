export type ExportDocumentData = {
  title: string;
  evaluation: DocumentEvaluationResult;
  themePrimaryColor?: string;
  themeAccentColor?: string;
  isDarkMode?: boolean;
};

export type ExportResult = {
  success: boolean;
  message: string;
};

// Safe native module detector: checks registries without invoking throwing getters
export const isNativeModuleAvailable = (moduleName: string): boolean => {
  if (Platform.OS === 'web') return false;
  try {
    const globalObj = typeof globalThis !== 'undefined' ? (globalThis as any) : (global as any);
    // Check ExpoModules / expo.modules registry
    if (globalObj?.expo?.modules?.[moduleName]) return true;
    if (globalObj?.ExpoModules?.[moduleName]) return true;
    if (globalObj?.NativeModulesProxy?.[moduleName]) return true;
    // Check NativeModules
    if (NativeModules && NativeModules[moduleName]) return true;
    return false;
  } catch {
    return false;
  }
};

export const isViewShotAvailable = (): boolean => {
  if (Platform.OS === 'web') return false;
  try {
    if (TurboModuleRegistry && typeof TurboModuleRegistry.get === 'function') {
      return TurboModuleRegistry.get('RNViewShot') != null;
    }
    return (NativeModules && NativeModules['RNViewShot']) != null;
  } catch {
    return false;
  }
};

export const isPrintAvailable = (): boolean => {
  return isNativeModuleAvailable('ExpoPrint');
};

export const isSharingAvailable = (): boolean => {
  return isNativeModuleAvailable('ExpoSharing');
};

const getPrintModule = () => {
  if (!isPrintAvailable()) return null;
  try {
    return require('expo-print');
  } catch (e) {
    return null;
  }
};

const getSharingModule = () => {
  if (!isSharingAvailable()) return null;
  try {
    return require('expo-sharing');
  } catch (e) {
    return null;
  }
};

const getViewShotModule = () => {
  if (!isViewShotAvailable()) return null;
  try {
    return require('react-native-view-shot');
  } catch (e) {
    return null;
  }
};

/**
 * Formats a clean, proportional ASCII text receipt for sharing across messaging apps
 */
export const formatReceiptText = (data: ExportDocumentData): string => {
  const { title, evaluation } = data;
  const dateStr = new Date().toLocaleString();
  const divider = '==========================================';
  const dashed = '------------------------------------------';

  const rows = evaluation.lines
    .filter((l) => !l.isComment || l.rawText.trim().length > 0)
    .map((l) => {
      const num = String(l.lineNumber).padStart(2, ' ');
      if (l.isComment) {
        return ` ${num} | ${l.rawText}`;
      }
      const text = (l.rawText || '').padEnd(24, ' ').slice(0, 24);
      const res = (l.resultText || '').padStart(12, ' ');
      return ` ${num} | ${text} | ${res}`;
    });

  return [
    divider,
    `         CALCNOTE EVOLUTION RECEIPT       `,
    `  ${(title || 'CALCULATION SHEET').toUpperCase()}`,
    `  Date: ${dateStr}`,
    divider,
    ` LN | ITEM / FORMULA            | AMOUNT     `,
    dashed,
    ...rows,
    divider,
    ` TOTAL (NET BALANCE): ${evaluation.formattedGrandTotal.padStart(20, ' ')}`,
    divider,
    ` Verified • ${evaluation.solvedCount} calculated lines`,
    ` Generated by NoteCalc Pro`,
    divider,
  ].join('\n');
};

